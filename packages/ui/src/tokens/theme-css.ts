import { colors, moduleColors, THEMES, type Theme } from './color'
import { radius, SPACING_UNIT } from './layout'
import { fontFamily, fontSize } from './typography'

const kebab = (value: string): string => value.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

const themeVariables = (theme: Theme): string[] => [
  ...Object.entries(colors[theme]).map(([name, value]) => `--color-${kebab(name)}: ${value};`),
  ...Object.entries(moduleColors).map(([id, value]) => `--color-module-${id}: ${value[theme]};`),
]

const indent = (lines: string[], depth: number): string =>
  lines.map((line) => `${'  '.repeat(depth)}${line}`).join('\n')

/** Generates the Tailwind v4 / Uniwind theme from TS tokens (single source of truth). */
export const buildThemeCss = (): string => {
  const staticTokens = [
    `--spacing: ${SPACING_UNIT}px;`,
    ...Object.entries(radius).map(([name, value]) => `--radius-${name}: ${value}px;`),
    ...Object.entries(fontFamily).map(([name, value]) => `--font-${kebab(name)}: '${value}';`),
    ...Object.entries(fontSize).flatMap(([name, [size, lineHeight]]) => [
      `--text-${name}: ${size}px;`,
      `--text-${name}--line-height: ${lineHeight}px;`,
    ]),
  ]

  const variants = THEMES.map(
    (theme) => `    @variant ${theme} {\n${indent(themeVariables(theme), 3)}\n    }`,
  ).join('\n')

  return [
    '/* GENERATED by packages/ui/scripts/build-theme.ts — do not edit. Edit src/tokens/* instead. */',
    `@theme {\n${indent(staticTokens, 1)}\n}`,
    `@layer theme {\n  :root {\n${variants}\n  }\n}`,
    '',
  ].join('\n\n')
}
